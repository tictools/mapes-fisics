def load(file_name):
    """Features of a Natural Earth GeoJSON file (read once)."""
    if file_name not in _layer_cache:
        with open(os.path.join(NE_DIR, file_name + GEOJSON_EXT), encoding=ENCODING) as handle:
            _layer_cache[file_name] = json.load(handle)['features']
    return _layer_cache[file_name]


# ================================================================ projection
class LAEA:
    """Lambert azimuthal equal-area projection (km)."""

    def __init__(self, lon0, lat0):
        self.centre_lon, self.centre_lat = np.radians(lon0), np.radians(lat0)

    def __call__(self, lon, lat):
        lon, lat = np.radians(np.asarray(lon, float)), np.radians(np.asarray(lat, float))
        delta_lon = lon - self.centre_lon
        scale = np.sqrt(2 / (1 + np.sin(self.centre_lat) * np.sin(lat)
                             + np.cos(self.centre_lat) * np.cos(lat) * np.cos(delta_lon)))
        return (scale * np.cos(lat) * np.sin(delta_lon) * EARTH_RADIUS_KM,
                scale * (np.cos(self.centre_lat) * np.sin(lat)
                         - np.sin(self.centre_lat) * np.cos(lat) * np.cos(delta_lon)) * EARTH_RADIUS_KM)


class Frame:
    """Projection + conversion to viewBox coordinates."""

    def __init__(self, lon0, lat0, extent):
        self.project = LAEA(lon0, lat0)
        xs, ys = self.project([point[0] for point in extent], [point[1] for point in extent])
        self.x_min, self.x_max, self.y_min, self.y_max = xs.min(), xs.max(), ys.min(), ys.max()
        self.scale = VIEWBOX_WIDTH / (self.x_max - self.x_min)
        self.height = round((self.y_max - self.y_min) * self.scale)

    def xy(self, lon, lat):
        x, y = self.project(lon, lat)
        return (x - self.x_min) * self.scale, (self.y_max - y) * self.scale

    def point(self, lon_lat):
        x, y = self.xy(lon_lat[0], lon_lat[1])
        return [round(float(x), COORD_DECIMALS), round(float(y), COORD_DECIMALS)]


# ================================================================ geometry
def polygons(geometry):
    if geometry['type'] == 'Polygon':
        return [geometry['coordinates']]
    return geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else []


def linestrings(geometry):
    if geometry['type'] == 'LineString':
        return [geometry['coordinates']]
    return geometry['coordinates'] if geometry['type'] == 'MultiLineString' else []


def simplify(points, tolerance):
    """Iterative Ramer–Douglas–Peucker."""
    if len(points) < MIN_RING_POINTS:
        return points
    keep = np.zeros(len(points), bool)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        i, j = stack.pop()
        if j <= i + 1:
            continue
        start, end = points[i], points[j]
        between = points[i + 1:j]
        direction = end - start
        length = np.hypot(*direction)
        if length == 0:
            distances = np.hypot(*(between - start).T)
        else:
            distances = np.abs(direction[0] * (between[:, 1] - start[1])
                               - direction[1] * (between[:, 0] - start[0])) / length
        farthest = int(np.argmax(distances))
        if distances[farthest] > tolerance:
            split = i + 1 + farthest
            keep[split] = True
            stack += [(i, split), (split, j)]
    return points[keep]


def path(points):
    """SVG path of a polyline, one decimal per coordinate."""
    return PATH_MOVE + PATH_LINE.join(f'{x:.1f},{y:.1f}' for x, y in points)


def in_view(frame, points, padding=IN_VIEW_PADDING):
    return not (points[:, 0].max() < -padding or points[:, 0].min() > VIEWBOX_WIDTH + padding
                or points[:, 1].max() < -padding or points[:, 1].min() > frame.height + padding)


def to_view(frame, coordinates):
    """GeoJSON coordinates -> viewBox points (n×2 array)."""
    lon_lat = np.array(coordinates)[:, :2]
    x, y = frame.xy(lon_lat[:, 0], lon_lat[:, 1])
    return np.column_stack([x, y])


def shoelace_area(points):
    return abs(np.sum(points[:-1, 0] * points[1:, 1] - points[1:, 0] * points[:-1, 1])) / 2


def polygons_path(frame, polygon_list, tolerance, min_area=0):
    """SVG path of polygons; polygons whose outer ring is smaller than min_area are skipped."""
    out = []
    for polygon in polygon_list:
        for ring_index, ring in enumerate(polygon):
            points = to_view(frame, ring)
            if not in_view(frame, points):
                continue
            if ring_index == 0 and min_area:
                if shoelace_area(points) < min_area:
                    break
            points = simplify(points, tolerance)
            if len(points) >= MIN_RING_POINTS:
                out.append(path(points) + PATH_CLOSE)
    return ''.join(out)


def lines_path(frame, line_list, tolerance):
    out = []
    for line in line_list:
        points = to_view(frame, line)
        if not in_view(frame, points):
            continue
        points = simplify(points, tolerance)
        if len(points) >= MIN_PATH_POINTS:
            out.append(path(points))
    return ''.join(out)


def ring_area(ring):
    return shoelace_area(np.array(ring))


def ring_within(ring, box):
    """Whether every point of the ring is inside box [min_lon, min_lat, max_lon, max_lat]."""
    min_lon, min_lat, max_lon, max_lat = box
    points = np.array(ring)[:, :2]
    return bool(np.all((points[:, 0] >= min_lon) & (points[:, 0] <= max_lon)
                       & (points[:, 1] >= min_lat) & (points[:, 1] <= max_lat)))


def source_polygons(refs):
    """Polygons of an area feature, in the order of its source refs."""
    out = []
    for ref in refs:
        file_name, name_key = LAYERS[ref['layer']]
        found = [polygon for ne_feature in load(file_name) if ne_feature['properties'].get(name_key) == ref['name']
                 for polygon in polygons(ne_feature['geometry'])]
        if 'within' in ref:
            found = [polygon for polygon in found if ring_within(polygon[0], ref['within'])]
        if not found:
            raise SystemExit(f"Not found in Natural Earth: {ref['layer']} {ref['name']!r}"
                             + (f" within {ref['within']}" if 'within' in ref else ''))
        out += [max(found, key=lambda polygon: ring_area(polygon[0]))] if ref.get('largest') else found
    return out


def river_lines(refs):
    file_name, name_key = LAYERS[LAYER_RIVERS]
    names = {ref['name'] for ref in refs}
    found = [line for ne_feature in load(file_name) if ne_feature['properties'].get(name_key) in names
             for line in linestrings(ne_feature['geometry'])]
    if not found:
        raise SystemExit(f'River not found in Natural Earth: {sorted(names)}')
    return found


def inside(polygon_list, lon_lat):
    """Whether (lon, lat) is inside the polygons (even-odd over every ring, so holes count)."""
    x, y = lon_lat
    hit = False
    for polygon in polygon_list:
        for ring in polygon:
            points = np.array(ring)[:, :2]
            x0, y0, x1, y1 = points[:-1, 0], points[:-1, 1], points[1:, 0], points[1:, 1]
            crosses = (y0 > y) != (y1 > y)
            with np.errstate(divide='ignore', invalid='ignore'):
                x_cross = x0 + (y - y0) * (x1 - x0) / (y1 - y0)
            hit ^= bool(np.count_nonzero(crosses & (x < x_cross)) % 2)
    return hit


def snap_to_lines(frame, line_list, lon_lat):
    """Point on the line (river) closest to the reference point."""
    best, best_distance = None, np.inf
    target_x, target_y = frame.xy(*lon_lat)
    for line in line_list:
        points = to_view(frame, line)
        x, y = points[:, 0], points[:, 1]
        distances = (x - target_x) ** 2 + (y - target_y) ** 2
        nearest = int(np.argmin(distances))
        if distances[nearest] < best_distance:
            best_distance = distances[nearest]
            best = [round(float(x[nearest]), COORD_DECIMALS), round(float(y[nearest]), COORD_DECIMALS)]
    return best


# ================================================================ base layer (blank map)
def graticule_path(frame, settings):
    paths = []
    meridian_lats = np.linspace(*settings['meridian_lats'], MERIDIAN_SAMPLES)
    for lon in range(MERIDIAN_LON_RANGE[0], MERIDIAN_LON_RANGE[1] + 1, GRATICULE_STEP_DEG):
        x, y = frame.xy(np.full_like(meridian_lats, lon), meridian_lats)
        paths.append(path(simplify(np.column_stack([x, y]), GRATICULE_TOLERANCE)))
    first_parallel, last_parallel = settings['parallels']
    for lat in range(first_parallel, last_parallel + 1, GRATICULE_STEP_DEG):
        parallel_lons = np.linspace(*settings['parallel_lons'], PARALLEL_SAMPLES)
        x, y = frame.xy(parallel_lons, np.full_like(parallel_lons, lat))
        points = np.column_stack([x, y])
        points = points[(points[:, 0] > -PARALLEL_MARGIN) & (points[:, 0] < VIEWBOX_WIDTH + PARALLEL_MARGIN)]
        if len(points) > 1:
            paths.append(path(simplify(points, GRATICULE_TOLERANCE)))
    return ''.join(paths)


def base_layers(frame, graticule_config=None):
    settings = {**DEFAULT_GRATICULE, **(graticule_config or {})}
    regions = load(LAYERS[LAYER_REGIONS][0])

    def relief(feature_class):
        return ''.join(polygons_path(frame, polygons(region['geometry']), RELIEF_TOLERANCE, RELIEF_MIN_AREA)
                       for region in regions if region['properties'][REGION_CLASS_KEY] == feature_class)

    land = ''.join(polygons_path(frame, polygons(part['geometry']), LAND_TOLERANCE, LAND_MIN_AREA)
                   for part in load(LAND_FILE))
    lakes = ''.join(polygons_path(frame, polygons(lake['geometry']), LAKES_TOLERANCE, LAKES_MIN_AREA)
                    for lake in load(LAYERS[LAYER_LAKES][0]))
    minor_rivers = ''.join(lines_path(frame, linestrings(river['geometry']), MINOR_RIVERS_TOLERANCE)
                           for river in load(LAYERS[LAYER_RIVERS][0])
                           if river['properties'].get(SCALERANK_KEY, DEFAULT_SCALERANK) <= MINOR_RIVER_MAX_SCALERANK)
    return {'graticule': graticule_path(frame, settings), 'land': land, 'plateaus': relief(CLASS_PLATEAU),
            'mountains': relief(CLASS_RANGE), 'lakes': lakes, 'rivers': minor_rivers}


# ================================================================ features
def build(frame, features, warnings):
    """Feature configs -> generated features (viewBox units). Appends geometry warnings."""
    built = []
    for config in features:
        kind = config['kind']
        feature = {'id': config['id'], 'name': config['name'], 'group': config['group'], 'kind': kind}
        if kind == KIND_AREA:
            source = source_polygons(config['source'])
            feature['d'] = polygons_path(frame, source, AREA_TOLERANCE)
            feature['dot'] = frame.point(config['dot'])
            if not inside(source, config['dot']):
                warnings.append(f"{config['id']}: dot outside its area (move it well inside the polygon)")
        elif kind == KIND_RIVER:
            source = river_lines(config['source'])
            feature['d'] = lines_path(frame, source, RIVER_TOLERANCE)
            feature['dot'] = snap_to_lines(frame, source, config['dot'])
        elif kind == KIND_LINE:  # strait
            feature['d'] = path(np.array([frame.xy(*point) for point in config['coords']]))
            feature['dot'] = frame.point(config['dot'])
        elif kind == KIND_PEAK:
            feature['dot'] = frame.point(config['dot'])
        label = config.get('label')
        dot_x, dot_y = feature['dot']
        feature['label'] = (frame.point(label) if label
                            else [dot_x, round(dot_y - DEFAULT_LABEL_OFFSET, COORD_DECIMALS)])
        built.append(feature)
    return built


# ================================================================ region configs
def valid_box(box):
    """Whether box is [min_lon, min_lat, max_lon, max_lat] with min < max."""
    if not isinstance(box, list) or len(box) != WITHIN_BOX_SIZE:
        return False
    if not all(isinstance(value, (int, float)) for value in box):
        return False
    min_lon, min_lat, max_lon, max_lat = box
    return min_lon < max_lon and min_lat < max_lat


def validate(config):
    """Returns a list of problems in a region config (empty if it is valid)."""
    errors = [f'missing key {key!r}' for key in REQUIRED_REGION_KEYS if key not in config]
    if errors:
        return errors
    if config['projection'].get('type') != PROJECTION_LAEA:
        errors.append(f'projection.type must be "{PROJECTION_LAEA}"')
    ids, names = set(), set()
    for index, feature in enumerate(config['features']):
        where = f"feature {index} ({feature.get('id', '?')})"
        errors += [f'{where}: missing {key!r}' for key in REQUIRED_FEATURE_KEYS if key not in feature]
        if feature.get('id') in ids:
            errors.append(f'{where}: duplicate id')
        if feature.get('name') in names:
            errors.append(f'{where}: duplicate name')
        ids.add(feature.get('id'))
        names.add(feature.get('name'))
        if not re.fullmatch(ID_PATTERN, str(feature.get('id', ''))):
            errors.append(f'{where}: id must be lowercase ascii letters, digits or _')
        group, kind = feature.get('group'), feature.get('kind')
        if group not in GROUPS:
            errors.append(f'{where}: unknown group {group!r} (known: {", ".join(GROUPS)})')
        elif kind not in GROUPS[group]:
            errors.append(f'{where}: kind {kind!r} not allowed for {group} (allowed: {sorted(GROUPS[group])})')
        if kind in SOURCE_KINDS:
            refs = feature.get('source') or []
            if not refs:
                errors.append(f'{where}: {kind} needs a non-empty source')
            for ref in refs:
                if ref.get('layer') not in LAYERS:
                    errors.append(f"{where}: unknown layer {ref.get('layer')!r} (known: {', '.join(LAYERS)})")
                elif (kind == KIND_RIVER) != (ref['layer'] == LAYER_RIVERS):
                    errors.append(f"{where}: {kind} cannot use layer {ref['layer']!r}")
                if 'within' in ref and not valid_box(ref['within']):
                    errors.append(f'{where}: within must be [min_lon, min_lat, max_lon, max_lat]')
        if kind == KIND_LINE and len(feature.get('coords') or []) < MIN_LINE_POINTS:
            errors.append(f'{where}: line needs at least {MIN_LINE_POINTS} coords')
        if kind in MANUAL_KINDS and not feature.get('manual'):
            errors.append(f'{where}: {kind} geometry is drawn by hand; mark it "manual": true')
    return errors


def split_label(name):
    """Same rule as splitLabel() in js/app.js: long names wrap at the space nearest the middle."""
    if len(name) <= LABEL_MAX_CHARS:
        return [name]
    middle = len(name) / 2
    spaces = [index for index, char in enumerate(name) if char == SPACE]
    if not spaces:
        return [name]
    best = min(spaces, key=lambda index: abs(index - middle))
    return [name[:best], name[best + 1:]]


def label_box(feature):
    """Approximate label box (left, top, right, bottom) in viewBox units; confirm in the browser."""
    lines = split_label(feature['name'])
    width = max(len(line) for line in lines) * LABEL_CHAR_WIDTH + LABEL_PADDING_X
    height = len(lines) * LABEL_LINE_HEIGHT + LABEL_PADDING_Y
    x, y = feature['label']
    return x - width / 2, y - height / 2, x + width / 2, y + height / 2


def boxes_overlap(first, second):
    return first[0] < second[2] and second[0] < first[2] and first[1] < second[3] and second[1] < first[3]


def layout_warnings(data):
    """Labels that overlap or cover other dots, and dots or labels outside the map."""
    out = list(data.pop(WARNINGS_KEY, []))
    width, height = data['viewBox'][2], data['viewBox'][3]
    features = data['features']
    boxes = [label_box(feature) for feature in features]
    for feature, box in zip(features, boxes):
        x, y = feature['dot']
        if not (0 <= x <= width and 0 <= y <= height):
            out.append(f"{feature['id']}: dot outside the map ({x}, {y})")
        if box[0] < 0 or box[1] < 0 or box[2] > width or box[3] > height:
            out.append(f"{feature['id']}: label partly outside the map")
        if not feature.get('d') and feature['kind'] != KIND_PEAK:
            out.append(f"{feature['id']}: empty geometry (is the feature inside the extent?)")
    for i in range(len(features)):
        for j in range(i + 1, len(features)):
            if boxes_overlap(boxes[i], boxes[j]):
                out.append(f"{features[i]['id']} / {features[j]['id']}: labels overlap")
    for feature, box in zip(features, boxes):
        for other in features:
            x, y = other['dot']
            dot_box = (x - DOT_RADIUS, y - DOT_RADIUS, x + DOT_RADIUS, y + DOT_RADIUS)
            if other is not feature and boxes_overlap(box, dot_box):
                out.append(f"{feature['id']}: label covers the dot of {other['id']}")
    return out


def region_paths(region_ids):
    if region_ids:
        return [os.path.join(REGIONS_DIR, region_id + CONFIG_EXT) for region_id in region_ids]
    return sorted(config_path for config_path in glob.glob(os.path.join(REGIONS_DIR, '*' + CONFIG_EXT))
                  if os.path.basename(config_path) != NAMES_FILE)


def frame_of(config):
    projection = config['projection']
    return Frame(projection['lon0'], projection['lat0'], config['extent'])


def report(config_path, data):
    warnings = layout_warnings(data)
    status = 'OK' if not warnings else f'{len(warnings)} warning(s)'
    print(f"{os.path.relpath(config_path)}: {status} ({len(data['features'])} features)", *warnings, sep='\n  - ')
    return warnings


def build_region(config):
    frame = frame_of(config)
    warnings = []
    data = {'id': config['id'], 'title': config['title'], 'viewBox': [0, 0, VIEWBOX_WIDTH, frame.height],
            'base': base_layers(frame, config.get('graticule')), 'features': build(frame, config['features'], warnings)}
    data[WARNINGS_KEY] = warnings  # removed by layout_warnings() before saving
    return data


def save(data):
    key = data['id']
    os.makedirs(OUT_DIR, exist_ok=True)
    data_path = os.path.join(OUT_DIR, key + DATA_EXT)
    with open(data_path, 'w', encoding=ENCODING) as handle:
        handle.write(DATA_HEADER)
        handle.write(DATA_ASSIGN.format(key=json.dumps(key)))
        json.dump(data, handle, ensure_ascii=False, separators=JSON_SEPARATORS)
        handle.write(DATA_FOOTER)
    print(f'  wrote {os.path.relpath(data_path)} ({round(os.path.getsize(data_path) / BYTES_PER_KB)} KB)')


def main(argv):
    check = CHECK_FLAG in argv
    region_ids = [arg for arg in argv if not arg.startswith(OPTION_PREFIX)]
    failed = False
    for config_path in region_paths(region_ids):
        with open(config_path, encoding=ENCODING) as handle:
            config = json.load(handle)
        errors = validate(config)
        if config.get('id') != os.path.splitext(os.path.basename(config_path))[0]:
            errors.append('id must match the file name')
        if errors:
            failed = True
            print(f'{os.path.relpath(config_path)}:', *errors, sep='\n  - ')
            continue
        try:
            data = build_region(config)
        except SystemExit as missing:  # a source is not in Natural Earth
            failed = True
            print(f'{os.path.relpath(config_path)}:', missing, sep='\n  - ')
            continue
        if report(config_path, data) and check:
            failed = True
        if not check:
            save(data)
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
